const tables: Record<AppLocale, Dict> = { ru, en };

export function translate(
	locale: AppLocale,
	key: string,
	vars?: Record<string, string | number>
): string {
	let text = tables[locale][key] ?? tables.ru[key] ?? key;
	if (vars) {
		for (const [name, value] of Object.entries(vars)) {
			text = text.replaceAll(`{${name}}`, String(value));
		}
	}
	return text;
}

/** Maps AppError message keys (and unknown errors) to localized copy. */
export function translateError(
	locale: AppLocale,
	err: unknown,
	fallbackKey = 'errors.generic'
): string {
	const msg = errorMessage(err);
	if (msg && (tables[locale][msg] || tables.ru[msg])) {
		return translate(locale, msg);
	}
	const code =
		err && typeof err === 'object' && 'code' in err
			? String((err as { code: unknown }).code)
			: '';
	if (code === 'PGRST301' || code === '401' || code === '403') {
		return translate(locale, 'errors.needAuth');
	}
	return translate(locale, fallbackKey);
}

function errorMessage(err: unknown): string {
	if (err instanceof Error) return err.message.trim();
	if (err && typeof err === 'object' && 'message' in err) {
		const m = (err as { message: unknown }).message;
		if (typeof m === 'string') return m.trim();
	}
	return '';
}

export function titleCaseEn(value: string): string {
	return value
		.split(' ')
		.map((part) => (part ? part[0]!.toUpperCase() + part.slice(1) : part))
		.join(' ');
}
